"""Rock Band 3 Deluxe crash analysis for RPCS3 logs and RB3Enhanced Xbox 360 .exc dumps.

Standard library only. Function/class names come from rb3dx_crash_data.json.gz, generated by
rb3dx-crasher/build_bot_data.py from the RB3 decomp symbols and the current DX EBOOT.

Public API:
    analyze_rpcs3(lines)  -> (summary_markdown, debug_text)   # lines of an RPCS3 log
    analyze_exc(path)     -> (summary_markdown, debug_text)   # RB3E .exc dump
"""
import bisect, gzip, json, os, re, struct, zlib
from collections import Counter, defaultdict

DATA_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'rb3dx_crash_data.json.gz')
_DATA = None

RSX_LOCAL = (0xC0000000, 0x0F900000)  # 249 MB of video memory available to games
STACK_LO, STACK_HI = 0xD0000000, 0xE0000000


# ============================================================== symbol data

class _Funcs:
    def __init__(self, rows, files):
        self.rows = rows
        self.starts = [r[0] for r in rows]
        self.files = files

    def find(self, a):
        i = bisect.bisect_right(self.starts, a) - 1
        if i >= 0:
            r = self.rows[i]
            if r[0] <= a < r[0] + max(r[1], 4):
                return r
        return None

    def name(self, a, trusted=False):
        r = self.find(a)
        if not r or not r[2]:
            return ''
        if trusted and len(r) > 4 and r[4] in ('g', 'c'):
            return ''
        return r[2]

    def label(self, a, ps3=False):
        r = self.find(a)
        if not r:
            return '(not in game code)'
        base = f'fn_{r[0]:08X}+0x{a - r[0]:x}'
        if r[2]:
            src = self.files[r[3]] if r[3] >= 0 else ''
            conf = ''
            if ps3 and len(r) > 4:
                conf = {'s': '', 'l': ' (likely)', 'g': ' (guess)', 'c': ' (guess)', 'h': ' (message handler)', 'x': ''}.get(r[4], '')
            return f'{r[2]}{conf}' + (f' [{src}]' if src else '') + f'  ({base})'
        return base


def _data():
    global _DATA
    if _DATA is None:
        if not os.path.exists(DATA_PATH):
            _DATA = {}
            return _DATA
        with gzip.open(DATA_PATH, 'rb') as fh:
            d = json.loads(fh.read())
        files = d['files']
        x, p = d['x360'], d['ps3']
        _DATA = {
            'x_funcs': _Funcs(x['funcs'], files),
            'x_text': tuple(x['text']),
            'x_vt': {int(k): v for k, v in x['vtables'].items()},
            'x_str': {int(k): v for k, v in x['strings'].items()},
            'p_funcs': _Funcs(p['funcs'], files),
            'p_text': tuple(p['text']),
            'p_block': p['block'],
            'p_sums': bytes.fromhex(p['sums']),
            'p_vt': {int(k): v for k, v in p['vtables'].items()},
            'built': d.get('built', ''),
        }
    return _DATA


# ============================================================== shared helpers

SCRIPT_RE = re.compile(r'^(DataArray::\w+|DataNode::\w+|DataFuncObj::Handle|Data[A-Z][A-Za-z]*)$')

def _script_summary(names):
    """Returns (lines, info) describing script involvement in a stack of function names."""
    interp = [bool(SCRIPT_RE.match(n or '')) for n in names]
    if not any(interp):
        return [], None
    first = interp.index(True)
    last = len(interp) - 1 - interp[::-1].index(True)
    out = ['A DTA script was running.']
    called = None
    if first == 0:
        k = next((i for i in range(1, len(names)) if names[i] and not interp[i]), None)
        out.append('The crash is inside the script itself: a command used a null/deleted value '
                   '(e.g. a method call on an unset `$var` or a missing object).')
        if k is not None and k < last:
            out.append(f'That script block was being run by `{names[k]}`.')
    else:
        called = names[first - 1] or names[0]
        out.append(f'The script called into engine code that crashed (`{called}`).' if called else
                   'The script called into engine code that crashed.')
    chain = []
    for i in range(last + 1, len(names)):
        if not names[i]:
            if chain:
                break
            continue
        chain.append(names[i])
        if len(chain) == 3:
            break
    if chain:
        out.append('The script was started by `' + '` <- `'.join(chain) + '`.')
    return out, {'first': first, 'last': last, 'trigger': chain, 'called': called}

GENERIC = re.compile(r'^(Hmx::Object::\w+|ObjectDir::Handle|MsgSource::\w+|MsgSource::Sink::\w+|UIPanel::(Enter|Handle|Poll)|'
                     r'UIComponent::\w+|PanelDir::\w+|Message::\w+|DataArrayMsg::\w+|App::\w+|main|entry)$')

def _pick_trigger(chain):
    for n in chain:
        if n and not GENERIC.match(n):
            return n
    return ''

def _fmt_time(t):
    return f'{int(t // 3600)}:{int(t % 3600 // 60):02d}:{t % 60:06.3f}'

def _log_time(line):
    m = re.match(r'·\S (\d+):(\d+):(\d+\.\d+)', line)
    return int(m[1]) * 3600 + int(m[2]) * 60 + float(m[3]) if m else None

def _song_of(path):
    m = re.search(r'/USRDIR/([^/]+)/songs/([^/]+)/', path)
    return (m.group(2), m.group(1)) if m else (None, None)

def _short(path):
    return path.split('/USRDIR/')[-1]


# ============================================================== RPCS3 logs

class _MemMap:
    def __init__(self, lines):
        self.blocks = []
        self.failed = []
        for l in lines:
            m = re.search(r'sys_memory_allocate\(\): Allocated (0x[0-9a-f]+) address \(size=(0x[0-9a-f]+)\)', l)
            if m:
                self.blocks.append((int(m.group(1), 16), int(m.group(2), 16)))
            m = re.search(r"'sys_memory_allocate' failed with 0x80010004 : CELL_ENOMEM, (0x[0-9a-f]+)", l)
            if m:
                self.failed.append(int(m.group(1), 16))
        self.blocks.sort()
        self.requests = [int(m.group(1), 16) for l in lines
                         for m in [re.search(r'sys_memory_allocate\(size=(0x[0-9a-f]+)', l)] if m]

    def main_heap(self):
        return max(self.blocks, key=lambda b: b[1]) if self.blocks else None

    def where(self, v):
        lo, size = RSX_LOCAL
        if lo <= v < 0xD0000000:
            if v >= lo + size:
                return f'0x{v - lo - size:X} bytes PAST THE END of video memory (249 MB)'
            return f'video memory +{(v - lo) / 1048576:.1f} MB'
        for a, n in self.blocks:
            if a <= v < a + n:
                return f'main memory block 0x{a:08X}-0x{a + n:08X}'
        for a, n in self.blocks:
            if a + n <= v < a + n + 0x400000:
                return f'0x{v - a - n:X} bytes PAST THE END of main memory block 0x{a:08X}-0x{a + n:08X} ({n / 1048576:.0f} MB)'
        return None


def _parse_dump(lines, fi):
    before = [i for i in range(max(0, fi - 2500), fi) if lines[i].strip() == 'Call stack:']
    after = [i for i in range(fi, min(len(lines), fi + 400)) if lines[i].strip() == 'Call stack:']
    if not before and not after:
        return {}, {}, [], None
    ci = before[-1] if before else after[0]
    regs, peeks, stack = {}, {}, None
    j = ci
    while j > 0 and ci - j < 400 and not re.match(r'^r0\s*:', lines[j]):
        j -= 1
    for l in lines[max(0, j - 15):ci]:
        m = re.match(r'^Stack: (0x[0-9a-f]+)\.\.(0x[0-9a-f]+)', l)
        if m:
            stack = (int(m.group(1), 16), int(m.group(2), 16))
    for l in lines[j:ci]:
        m = re.match(r'^(r\d+|LR|CTR|CIA|PC)\s*:\s*(0x[0-9a-fA-F]+)\s*(?:->\s*(.*))?', l)
        if m:
            regs[m.group(1)] = int(m.group(2), 16)
            if m.group(3):
                peeks[m.group(1)] = m.group(3).strip()
    frames = []
    for l in lines[ci + 1:ci + 80]:
        m = re.match(r'^(?:>\s*from\s+)?0x([0-9a-fA-F]+)', l.strip())
        if m:
            frames.append(int(m.group(1), 16))
        elif frames and not l.strip():
            break
    return regs, peeks, frames, stack


def _eboot_check(text, D):
    """Compare RPCS3's printed instruction listings with the DX EBOOT block checksums."""
    words = {}
    for a, b in re.findall(r'^\[([0-9a-f]{8})\]\s+((?:[0-9a-f]{2} ){3}[0-9a-f]{2}):', text, re.M):
        words[int(a, 16)] = bytes.fromhex(b.replace(' ', ''))
    tva, tsz = D['p_text']
    blk = D['p_block']
    checked = ok = 0
    starts = sorted({(a - tva) // blk for a in words if tva <= a < tva + tsz})
    for bi in starts:
        base = tva + bi * blk
        if all(base + k in words for k in range(0, blk, 4)):
            data = b''.join(words[base + k] for k in range(0, blk, 4))
            if bi * 2 + 2 <= len(D['p_sums']):
                checked += 1
                ok += struct.unpack_from('>H', D['p_sums'], bi * 2)[0] == (zlib.crc32(data) & 0xffff)
    if not checked:
        return None
    return ok == checked


def _odd_sizes(sizes):
    kinds = defaultdict(Counter)
    def kind(p):
        if '/songs/' not in p:
            return None
        m = re.search(r'(_keep\.png_ps3|\.png_ps3)$', p)
        return m.group(1) if m else None
    for p, sz in sizes.items():
        k = kind(p)
        if k:
            kinds[k][sz] += 1
    out = {}
    for p, sz in sizes.items():
        k = kind(p)
        if not k or kinds[k][sz] > 1:
            continue
        common = [(abs(sz - u), u, n) for u, n in kinds[k].items() if n >= 3 and u != sz]
        if common:
            d, u, n = min(common)
            if 0x40 <= d <= 0x800:
                out[p] = (sz, u, n)
    return out


def _describe_ps3(D, mem, v, peek=None):
    if v == 0:
        return 'null'
    tva, tsz = D['p_text']
    if tva <= v < tva + tsz:
        return D['p_funcs'].label(v, True)
    if peek and peek.startswith('"'):
        return peek
    if peek:
        try:
            w0 = int(peek.replace(' ', '')[:8], 16)
            if w0 in D['p_vt']:
                return f'object {D["p_vt"][w0]}'
        except ValueError:
            pass
    if v in D['p_vt']:
        return f'vtable of {D["p_vt"][v]}'
    if v < 0x10000:
        return 'small value'
    w = mem.where(v) if mem else None
    if w:
        return w
    t = v >> 28
    return {0x3: 'main memory', 0x1: 'EBOOT data / heap', 0xC: 'video memory', 0xD: 'stack'}.get(t, '')


def analyze_rpcs3(lines):
    """Crash analysis for an RPCS3 log. Returns (summary_markdown, debug_text); both empty if no crash."""
    D = _data()
    if not D:
        return '', ''
    lines = [l.rstrip('\n') for l in lines]
    text = '\n'.join(lines)
    fatals = [i for i, l in enumerate(lines) if l.startswith('·F ')]
    if not fatals:
        return '', ''
    boots = [i for i, l in enumerate(lines) if 'GUI: Boot successful' in l] or [0]
    events = []
    for fi in fatals:
        bi = max([b for b in boots if b <= fi] or [0])
        if not events or events[-1][1] != bi:
            events.append((fi, bi))

    sizes = {}
    for l in lines:
        m = re.search(r"sys_fs_open\(\): fd=\d+, Regular file, '([^']+)'.*?Pos/Size: \d+/[^(]*\(0x[0-9a-f]+/(0x[0-9a-f]+)\)", l)
        if m:
            sizes[m.group(1)] = int(m.group(2), 16)
    odd = _odd_sizes(sizes)
    match = _eboot_check(text, D)

    dbg = ['=== RB3DX CRASH ANALYSIS ===', f'symbol data built {D["built"]}']
    if match is False:
        dbg.append('WARNING: this log\'s code does not match the current RB3DX EBOOT; function names may be wrong '
                   '(the player is probably on an older or newer RB3DX).')
    elif match:
        dbg.append('EBOOT matches the current RB3DX build.')
    if len(boots) > 1:
        dbg.append(f'{len(boots)} game boots in this log, {len(events)} crashed.')
    if odd:
        dbg.append('Album art with an odd size (likely truncated/badly converted):')
        for pth, (sz, u, n) in sorted(odd.items()):
            dbg.append(f'  {_short(pth)}: 0x{sz:X} bytes, {n} others are 0x{u:X}')

    results = []
    for k, (fi, bi) in enumerate(events):
        res, d = _ps3_crash(D, lines, fi, bi, odd, k + 1, len(events), sizes)
        results.append(res)
        dbg += [''] + d
    sigs = [r['sig'] for r in results]
    if len(results) > 1 and len(set(sigs)) == 1:
        dbg.append('')
        dbg.append(f'All {len(results)} crashes share the same call stack: one reproducible bug.')

    # summary: one block per distinct crash type
    out = ['## Crash analysis :boom:']
    if match is False:
        out.append('_This log is from a different RB3DX build than the bot knows, so details may be off. '
                   'Make sure you are on the latest RB3DX._')
    seen = set()
    for r in results:
        key = r['title']
        if key in seen:
            continue
        seen.add(key)
        n = sum(1 for x in results if x['title'] == key)
        times = f' (x{n})' if n > 1 else ''
        out.append(f'- **{r["title"]}**{times}')
        if r['fix']:
            out.append(f'  {r["fix"]}')
        for fact in r['facts'][:4]:
            out.append(f'  - {fact}')
    if len(results) > 1 and len(set(sigs)) == 1:
        out.append(f'_All {len(results)} crashes in this log are the same bug._')
    return '\n'.join(out) + '\n', '\n'.join(dbg) + '\n'


def _ps3_crash(D, lines, fi, bi, odd, num, total, sizes_all=None):
    sizes_all = sizes_all or {}
    F = D['p_funcs']
    boot_lines = lines[bi:fi]
    mem = _MemMap(boot_lines)
    fatal = lines[fi]
    regs, peeks, frames, stack = _parse_dump(lines, fi)
    tcrash = _log_time(fatal) or 0
    tboot = _log_time(lines[bi]) if bi else None
    pc = None
    m = re.search(r'\[0x([0-9a-f]+)\]\}', fatal)
    if m:
        pc = int(m.group(1), 16)
    if pc is None and frames:
        pc = frames[0]
    if frames and pc is not None and frames[0] != pc:
        frames = [pc] + frames
    names = [F.name(a) for a in frames]
    tnames = [F.name(a, True) for a in frames]
    target = rw = None
    m = re.search(r'(reading|writing) location (0x[0-9a-f]+)', fatal)
    if m:
        rw, target = m.group(1), int(m.group(2), 16)

    # file activity in this boot
    opens = []
    for l in boot_lines:
        m = re.search(r'sys_fs_open\(path=“([^”]+)”', l) or re.search(r'sys_fs_open\(path="([^"]+)"', l)
        if m:
            opens.append((_log_time(l) or 0, m.group(1)))
    content = [(t, p) for t, p in opens if '/songs/' in p and not p.endswith(('songs.dta', 'songs.dtb'))]
    moggs = [(t, p) for t, p in opens if p.endswith('.mogg')]
    arts = [t for t, p in opens if p.endswith('_keep.png_ps3') and tcrash - t < 10]
    dtas = [(t, p) for t, p in opens if p.endswith(('.dta', '.dtb'))]
    last_content = content[-1] if content else None

    facts = []
    if tboot is not None:
        facts_time = f'{tcrash - tboot:.0f}s after the game booted'
    else:
        facts_time = ''
    song, pack = (None, None)
    if moggs:
        song, pack = _song_of(moggs[-1][1])
        song_secs = tcrash - moggs[-1][0]

    title, fix = None, ''
    blob = ' '.join(names)
    script_lines, script = _script_summary(names)
    if script:
        script['trigger'] = [n for n in tnames[script['last'] + 1:] if n][:6]

    def near(pat, n=4):
        return any(re.search(pat, x or '') for x in names[:n])

    ascii_ptr = target is not None and target >= 0x10000 and all(0x20 <= ((target >> sh) & 0xff) < 0x7f for sh in (24, 16, 8, 0))
    missing_song = any('missing_song_data' in v for v in peeks.values())

    # ---- classification (first match wins)
    if 'sys_net' in fatal:
        title = 'RPCS3 networking crash (emulator, not the game)'
        fix = 'Update RPCS3. If it keeps happening online, check your network setup with `!rpcn` and try turning UPnP off.'
    elif 'Compilation failed' in fatal:
        title = 'RPCS3 failed to compile game code (emulator, not the game)'
        fix = 'Clear your caches (`!caches`) and update RPCS3.'
    elif 'Access violation (local=' in fatal or ('Thread terminated due to fatal error' in fatal and 'local=' in fatal):
        mm = re.search(r'local=([^)\s]+)', fatal)
        f = mm.group(1) if mm else 'a file'
        title = 'RPCS3 crashed accessing a file on your PC'
        fix = (f'File: `{f}`. This is usually antivirus, OneDrive, or folder permissions. Move RPCS3 to `C:\\Games` and exclude it '
               f'from your antivirus.' + (' Delete the `currentsong` files and `discordrp.json` in USRDIR (`!gamedata`).'
                                          if 'currentsong' in f or 'discordrp' in f else ''))
    elif 'Verification failed' in fatal:
        title = 'RPCS3 internal error ("Verification failed")'
        fix = 'Update RPCS3 and tell us what you were doing when it happened.'
    elif near(r'AddHeap|MemInit') or (mem.failed and tboot is not None and tcrash - tboot < 60 and near(r'MemAlloc|MemHeap')):
        req = max(mem.requests) if mem.requests else 0
        avail = mem.failed[-1] if mem.failed else 0
        title = 'Not enough memory to start the game'
        fix = (f'The game asked RPCS3 for {req / 1048576:.0f} MB at boot' + (f' but only {avail / 1048576:.0f} MB was available' if avail else '') +
               '. Turn on **Debug Console Mode**, or delete `dx_high_memory.dta`. Use `!mem` for more info.')
    elif near(r'Locale::Init|SetSystemLanguage', 2):
        title = "The game couldn't load its language data at boot"
        fix = ('Its config is missing from the game files, so this install is broken, modded or mixed between versions. '
               'Reinstall RB3DX cleanly: delete the `gen` folder in RB3\'s `USRDIR` first, then copy the new files over.')
    elif near(r'ArchiveInit|PreInitSystem|ArkHash|Archive::'):
        title = "The game's archive files are broken or from different RB3DX versions"
        fix = 'Reinstall RB3DX cleanly: delete the `gen` folder in RB3\'s `USRDIR` first, then copy the new files over.'
    elif near(r'DataArray::Load|DataNode::Load|DataReadFile|DataReadString') and dtas and tcrash - dtas[-1][0] < 3:
        f = _short(dtas[-1][1])
        title = f'A game data file failed to load: `{f}`'
        if 'dx_high_memory' in f:
            fix = 'Your `dx_high_memory.dta` is corrupted. Delete it, then set high memory up again with `!mem`.'
        elif 'dx_settings' in f or 'dx_values' in f or 'dx_' in f:
            fix = f'Delete `{f}` (RB3DX will recreate it with defaults).'
        else:
            fix = 'That file is corrupted or has a syntax error. If it belongs to a custom song, remove or re-download that song.'
    elif ('memcpy' in names[:2] or near(r'RndTex|Texture')) and last_content and last_content[1].endswith('.png_ps3') \
            and tcrash - last_content[0] < 0.5:
        s, p = _song_of(last_content[1])
        bad = odd.get(last_content[1])
        title = f'Bad album art in song `{s}` ({p})' if bad else f'Crashed loading album art for `{s}` ({p})'
        fix = ('Its album art file is truncated/badly converted ' + (f'({bad[1] - bad[0]} bytes short). ' if bad and bad[0] < bad[1] else '') +
               'Remove or re-download that song, or ask its author to re-convert the art.')
    elif near(r'MemHeap::Alloc|MemAlloc|_MemAllocTemp|MemFree|MemHeap::Free', 3) and target is not None and target >= 0x10000:
        title = 'Memory corruption detected'
        fix = 'The game\'s memory bookkeeping was overwritten earlier. This is often bad custom content; see the files in the debug info.'
    elif near(r'MemHeap::Alloc|MemAlloc|_MemAllocTemp', 3):
        title = 'The game ran out of memory'
        dc = re.search(r'Debug Console Mode: (\w+)', text_cache(lines))
        fix = ('Turn on Debug Console Mode and set up high memory (`!mem`). ' if dc and dc.group(1) == 'false' else
               'You may have too many songs or heavy settings for available memory; check `!mem`. ') + \
              ('It happened while loading album art in the song list.' if arts else '')
    elif near(r'MemFree|MemHeap::Free'):
        title = 'Memory corruption detected'
        fix = 'Something earlier wrote over game memory. This is often bad custom content; see the files listed below.'
    elif near(r'NewTrackWatcherImpl') or pc == 0x00580b48:
        title = 'Bad song DTA: a song claims a part it does not have'
        fix = f'Song: `{song}` ({pack}). Report it to the song\'s author.' if song else 'Report the song to its author.'
    elif near(r'CurrentOutfitProvider') or pc == 0x003cdcf4:
        title = 'Editing a custom character crashed'
        fix = 'Please do not edit custom characters (prefabs).'
    elif stack and target is not None and stack[0] - 0x10000 <= target < stack[0]:
        title = 'Stack overflow (infinite recursion)'
        fix = 'A script or game function called itself forever. Send this log to the RB3DX devs.'
    elif last_content and last_content[1].endswith('.mogg') and tcrash - last_content[0] < 0.5:
        s, p = _song_of(last_content[1])
        title = f'Crashed loading the audio for `{s}` ({p})'
        fix = 'The song\'s audio (mogg) or its channel setup in songs.dta is probably bad. Report it to the song\'s author.'
    elif near(r'MusicLibrary|SongSort|NodeSort|MusicLibraryPanel', 6) or 'MusicLibrary' in blob:
        title = 'Crashed in the Music Library'
        fix = 'Send this log to the RB3DX devs and say what you pressed. If it happens on one song, name it.'
    elif near(r'GemPlayer|Player::|TrackWatcher|CommonPhraseCapturer|GemTrack|BandTrack|Beatmatch|VocalPlayer', 6) and song:
        title = f'Crashed during gameplay in `{song}` ({pack})'
        fix = (f'It crashed {song_secs:.0f}s into the song. If it crashes at the same spot every time, the chart is the problem: '
               'report it to the song\'s author. Otherwise send this log to the RB3DX devs.')
    elif script and missing_song:
        trig = _pick_trigger(script['trigger'])
        title = 'A script used data for a song that no longer exists' + (f' (in `{trig}`)' if trig else '')
        fix = ('The game looked up a song and got `missing_song_data` back. Usually a song that was removed or renamed is still '
               'referenced (setlist, last played, favorites). This is an RB3DX bug: send this log to the RB3DX devs.')
    elif script:
        trig = _pick_trigger(script['trigger'])
        called = next((n for n in tnames[:script['first']] if n), '')
        if called:
            title = f'Crash in `{called}`, called from a game script' + (f' (started by `{trig}`)' if trig else '')
        else:
            title = 'A game script crashed' + (f' (started by `{trig}`)' if trig else '')
        fix = 'This is probably an RB3DX bug. Send this log to the RB3DX devs and say what you were doing.'
    else:
        best = next((n for n in tnames if n), '')
        title = f'Game crash in `{best}`' if best else 'Game crash'
        fix = 'Send this log to the RB3DX devs and say what you were doing.'

    if facts_time:
        facts.append(f'Crashed {facts_time}.')
    if re.search(r"archive|language data", title or ''):
        ark = [(p, sizes_all.get(p)) for p in sorted(sizes_all) if re.search(r'/USRDIR/gen/patch_ps3(_\d+\.ark|\.hdr)$', p)]
        if ark:
            facts.append('Installed RB3DX files: ' + ', '.join(f'`{_short(p)}` {sz / 1048576:.0f} MB' if sz > 1048576 else f'`{_short(p)}` {sz / 1024:.0f} KB'
                                                                for p, sz in ark if sz))
    if song and title and song not in title and tcrash - moggs[-1][0] < 900 and len(arts) < 5:
        facts.append(f'Last song loaded: `{song}` ({pack}), {song_secs:.0f}s before the crash.')
    if opens and tcrash - opens[-1][0] < 2 and (_song_of(opens[-1][1])[0] or '~') not in title and not title.startswith('RPCS3'):
        facts.append(f'File opened right before the crash ({(tcrash - opens[-1][0]) * 1000:.0f} ms): `{_short(opens[-1][1])}`.')
    if len(arts) >= 5:
        facts.append('The player was scrolling the song list.')
    if ascii_ptr:
        facts.append(f'The bad pointer is text (`{target.to_bytes(4, "big").decode()}`): a string was used as an object.')

    # ---- debug text
    d = [f'--- Crash {num} of {total} ---' if total > 1 else '--- Crash ---', fatal[:300], f'Diagnosis: {title}']
    if fix:
        d.append(f'Advice: {fix}')
    for fct in facts:
        d.append(f'  {fct}')
    mh = mem.main_heap()
    if mh:
        d.append(f'main heap this boot: 0x{mh[0]:08X}-0x{mh[0] + mh[1]:08X} ({mh[1] / 1048576:.0f} MB)')
    if target is not None:
        tdesc = f'NULL pointer + 0x{target:X}' if target < 0x10000 else (mem.where(target) or _describe_ps3(D, mem, target))
        if ascii_ptr:
            tdesc = f'text {target.to_bytes(4, "big").decode()!r} used as a pointer (a string/symbol was treated as an object)'
        d.append(f'{rw} 0x{target:08X} -> {tdesc}')
    if pc is not None:
        d.append(f'PC {pc:08X}  {F.label(pc, True)}')
        if F.name(pc) == 'memcpy' and regs:
            d.append(f'  memcpy dst r3=0x{regs.get("r3", 0):08X} ({_describe_ps3(D, mem, regs.get("r3", 0))}), '
                     f'src r4=0x{regs.get("r4", 0):08X} ({_describe_ps3(D, mem, regs.get("r4", 0))}), bytes left r5={regs.get("r5", 0)}')
    if frames:
        d.append('Stack (most recent first):')
        for i, a in enumerate(frames):
            d.append(f'  #{i:<2} {a:08X}  {F.label(a, True)}')
        for l in script_lines:
            d.append('  => ' + l)
    if regs:
        d.append('Registers:')
        for i in range(32):
            k = f'r{i}'
            if k in regs and (regs[k] >= 0x10000 or i in (3, 4, 5)):
                d.append(f'  {k:<3} {regs[k]:08X}  {_describe_ps3(D, mem, regs[k], peeks.get(k))}')
    recent, seenp = [], set()
    for t, pth in reversed(opens):
        s = _short(pth)
        if s in seenp:
            continue
        seenp.add(s); recent.append((t, s))
        if len(recent) >= 10:
            break
    if recent:
        d.append('Last files opened:')
        for t, s in reversed(recent):
            d.append(f'  {_fmt_time(t)} ({(tcrash - t) * 1000:.0f} ms before)  {s}')
    errs = [l for l in boot_lines[-3000:] if l.startswith('·E ') and 'CELL_ENOENT' not in l and 'sys_fs' not in l]
    if errs:
        d.append('Last errors before the crash:')
        d += ['  ' + l[:220] for l in errs[-6:]]
    return {'title': title, 'fix': fix, 'facts': facts, 'sig': tuple(frames[:8])}, d


_TEXT_CACHE = {}
