# ============================================================== Xbox 360 .exc

EXC_CODES = {
    0xC0000005: 'access violation', 0xC000001D: 'illegal instruction', 0x80000003: 'breakpoint / assert',
    0xC00000FD: 'stack overflow', 0xC0000094: 'integer divide by zero', 0x80000002: 'misaligned data access',
}

class _Dump:
    def __init__(self, chunks):
        self.chunks = chunks
    def rd(self, a, n):
        for start, data in self.chunks:
            if start <= a and a + n <= start + len(data):
                return data[a - start:a - start + n]
        return None
    def u32(self, a):
        b = self.rd(a, 4)
        return struct.unpack('>I', b)[0] if b else None
    def cstr(self, a):
        for start, data in self.chunks:
            if start <= a < start + len(data):
                o = a - start
                e = data.find(b'\0', o, o + 200)
                if e < 0:
                    return None
                b = data[o:e]
                if len(b) >= 3 and all(32 <= ch < 127 for ch in b) and sum(ch in b'abcdefghijklmnopqrstuvwxyz_ABCDEFGHIJKLMNOPQRSTUVWXYZ' for ch in b) >= 2 and b'@@' not in b:
                    return b.decode()
                return None
        return None


def _region_360(v):
    if v == 0:
        return 'null'
    if v < 0x10000:
        return 'small value'
    return {0x4: 'heap', 0x5: 'heap', 0x7: 'stack', 0x8: 'image', 0x9: 'image', 0xA: 'physical', 0xB: 'physical',
            0xC: 'physical', 0xD: 'physical'}.get(v >> 28, 'garbage-looking')


def _describe_360(D, dump, v):
    F = D['x_funcs']
    if v == 0:
        return 'null'
    tva, tsz = D['x_text']
    if tva <= v < tva + tsz:
        return 'code ' + F.label(v)
    s = dump.cstr(v) or D['x_str'].get(v)
    if s:
        return repr(s[:80])
    if v in D['x_vt']:
        return f'vtable of {D["x_vt"][v]}'
    w0 = dump.u32(v)
    if w0 is not None and w0 in D['x_vt']:
        desc = f'object {D["x_vt"][w0]}'
        nm = dump.u32(v + 0x18)
        nms = dump.cstr(nm) if nm else None
        if nms:
            desc += f' named {nms!r}'
        return f'{_region_360(v)} {desc}'
    return _region_360(v)


def analyze_exc(path):
    D = _data()
    d = open(path, 'rb').read()
    if d[:4] != b'3EXX':
        return ('**This is not an Xbox 360 RB3Enhanced crash dump.**' if d[:3] != b'3EX' else
                '**Only Xbox 360 RB3Enhanced crash dumps are supported right now.**'), ''
    if not D:
        return '**Crash data file is missing on the bot.**', ''
    F = D['x_funcs']
    tag = d[8:56].split(b'\0')[0].decode(errors='replace')
    nsw, nmem = struct.unpack_from('>HH', d, 0x68)
    code, flags, _, addr, npar = struct.unpack_from('>5I', d, 0x6c)
    info = struct.unpack_from('>15I', d, 0x6c + 20)
    ctx = 0x6c + 0x50
    msr, iar, lr = struct.unpack_from('>III', d, ctx + 4)
    gpr = [struct.unpack_from('>Q', d, ctx + 0x18 + i * 8)[0] & 0xffffffff for i in range(32)]
    sw = ctx + 560
    stack = list(struct.unpack_from(f'>{nsw}I', d, sw))
    p = sw + 4 * nsw
    chunks = []
    for _ in range(nmem):
        if p + 8 > len(d):
            break
        a, n = struct.unpack_from('>II', d, p); p += 8
        chunks.append((a, d[p:p + n])); p += n
    dump = _Dump(chunks)

    tva, tsz = D['x_text']
    in_game = lambda a: tva <= a < tva + tsz
    frames = [addr] + stack
    if lr and (not stack or lr != stack[0]) and F.find(lr) and F.find(lr) is not F.find(addr):
        frames.insert(1, lr)
    names = [F.name(a) for a in frames]
    script_lines, script = _script_summary(names)
    kind = EXC_CODES.get(code, f'exception 0x{code:08X}')
    target = info[1] if code == 0xC0000005 and npar >= 2 else None
    rw = ('writing' if info[0] & 1 else 'reading') if target is not None else ''

    strings = []
    for start, data in chunks:
        if not (0x70000000 <= start < 0x80000000):
            continue
        for o in range(0, len(data) - 3, 4):
            v = struct.unpack_from('>I', data, o)[0]
            if v < 0x10000 or in_game(v):
                continue
            s = dump.cstr(v) or D['x_str'].get(v)
            item = repr(s[:60]) if s else None
            if not item:
                w0 = dump.u32(v)
                if w0 in D['x_vt']:
                    item = D['x_vt'][w0]
            if item and item not in strings:
                strings.append(item)

    def near(pat, n=4):
        return any(re.search(pat, x or '') for x in names[:n])
    blob = ' '.join(names)

    if not in_game(addr):
        title = 'Crash inside RB3Enhanced (or system) code'
        extra = ' It happened while the game was reading a song\'s MIDI, so one song may be broken.' if 'SongParser' in blob or 'Midi' in blob else ''
        fix = f'RB3Enhanced build `{tag}`. Update RB3Enhanced and RB3DX.{extra}'
    elif near(r'MemHeap::Alloc|MemAlloc|_MemAllocTemp', 3):
        title = 'The game ran out of memory'
        fix = 'The Xbox 360 has very little memory. Fewer custom songs, or turning off heavy RB3DX visuals, may help. Send this to the RB3DX devs.'
    elif re.search(r'BandSongMgr|SongMgr::|ContentMgr', blob):
        title = 'Crashed while loading songs/DLC'
        fix = 'A custom song or DLC package is probably broken' + (" (missing song data)" if "'missing_song_data'" in strings or any('missing_song_data' in s for s in strings) else '') + \
              '. Remove recently added songs to find it.'
    elif re.search(r'ArkHash|Archive|ArchiveInit', blob):
        title = "The game's archive files are broken"
        fix = 'Reinstall RB3DX cleanly.'
    elif 'RockCentral' in blob:
        title = 'Crash in an online (Rock Central) script'
        fix = 'Caused by the online server config script. Report it to the RB3Enhanced/RB3DX devs.'
    elif near(r'GemTrack::SetDir|AddPlayerDynamically|DoPostHandleAddPlayer', 3):
        title = 'Crash when a player dropped in mid-song'
        fix = 'Tell the RB3DX devs which instrument/controller joined and in which slot.'
    elif script:
        chain = [n for n in names[script['last'] + 1:] if n][:6]
        trig = _pick_trigger(chain)
        called = next((n for n in names[:script['first']] if n and not SCRIPT_RE.match(n)), '')
        if called:
            title = f'Crash in `{called}`, called from a game script' + (f' (started by `{trig}`)' if trig else '')
        else:
            title = 'A game script crashed' + (f' (started by `{trig}`)' if trig else '')
        fix = 'This is probably an RB3DX bug. Send this file to the RB3DX devs and say what you were doing.'
    else:
        best = next((n for n in names if n), '')
        title = f'Game crash in `{best}`' if best else 'Game crash'
        fix = 'Send this file to the RB3DX devs and say what you were doing.'

    summary = ['## Crash analysis :boom:', f'- **{title}**', f'  {fix}']
    if target is not None:
        summary.append(f'  - {kind} {rw} ' + (f'null + 0x{target:X}' if target < 0x10000 else f'0x{target:08X}'))
    msgs = [s for s in strings if re.match(r"^'[A-Za-z_][A-Za-z0-9_]{2,}'$", s)][:4]
    if msgs:
        summary.append('  - Names on the stack: ' + ', '.join(f'`{s.strip(chr(39))}`' for s in msgs))
    summary.append(f'\n**RB3Enhanced:** `{tag}`')

    dbg = ['=== RB3DX CRASH ANALYSIS (Xbox 360) ===', f'file: {os.path.basename(path)}', f'RB3Enhanced build: {tag}',
           f'Diagnosis: {title}', f'Advice: {fix}', '', f'{kind} at PC 0x{addr:08X}']
    if target is not None:
        dbg.append(f'{rw} 0x{target:08X} -> ' + (f'NULL pointer + 0x{target:X}' if target < 0x10000 else _describe_360(D, dump, target)))
    dbg.append('Stack (most recent first):')
    for i, a in enumerate(frames):
        dbg.append(f'  #{i:<2} {a:08X}  ' + (F.label(a) if in_game(a) else '(RB3Enhanced / system code)'))
    for l in script_lines:
        dbg.append('  => ' + l)
    dbg.append('Registers:')
    for i in range(32):
        if gpr[i] >= 0x10000 or i in (3, 4):
            dbg.append(f'  r{i:<2} {gpr[i]:08X}  {_describe_360(D, dump, gpr[i])}')
    dbg.append(f'  lr  {lr:08X}  {_describe_360(D, dump, lr)}')
    if strings:
        dbg.append('Strings and objects found on the stack:')
        dbg += ['  ' + s for s in strings[:40]]
    return '\n'.join(summary) + '\n', '\n'.join(dbg) + '\n'
